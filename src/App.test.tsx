// @vitest-environment jsdom
import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest'
import { cleanup, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import '@testing-library/jest-dom/vitest'
import App from './App'

vi.mock('recharts', () => {
  const Chart = ({ children }: { children?: React.ReactNode }) => <div>{children}</div>
  return { ResponsiveContainer: Chart, BarChart: Chart, Bar: () => null, CartesianGrid: () => null, XAxis: () => null, YAxis: () => null, Tooltip: () => null }
})
beforeEach(() => localStorage.clear())
beforeAll(() => {
  HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); this.querySelector<HTMLButtonElement>('button')?.focus() }
  HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); this.dispatchEvent(new Event('close')) }
})
afterEach(cleanup)

describe('educational calculator public interface', () => {
  it('starts empty in both sections without pie navigation or example controls', async () => {
    const user = userEvent.setup()
    render(<App />)
    expect(screen.getByLabelText('Serie de datos')).toHaveValue('')
    expect(screen.queryByTestId('metric-mean')).not.toBeInTheDocument()
    expect(screen.getByText('Tus datos, una nueva perspectiva')).toBeInTheDocument()
    expect(within(screen.getByRole('navigation')).getAllByRole('button')).toHaveLength(4)
    expect(screen.queryByRole('button', { name: /torta|ejemplo|alturas/i })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    expect(screen.getByLabelText('Elementos del espacio')).toHaveValue('')
    expect(screen.getByTestId('space-count')).toHaveTextContent('|Ω| = 0')
    expect(screen.queryByTestId('event-A')).not.toBeInTheDocument()
    expect(screen.queryByLabelText('Resultados equiprobables')).not.toBeInTheDocument()
    expect(screen.queryByLabelText('Escenario de ejemplo')).not.toBeInTheDocument()
    expect(screen.queryByLabelText('Permitir repetición')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: /Crear evento/ })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: /Guía rápida/ }))
    expect(screen.queryByText(/torta|ejemplo|precargad/i)).not.toBeInTheDocument()
  })

  it('recalculates manually entered data and handles invalid and empty inputs', async () => {
    const user = userEvent.setup()
    render(<App />)
    const input = screen.getByLabelText('Serie de datos')
    await user.type(input, '6, 7, 8, 6, 9, 7, 6, 10, 8, 7')
    expect(screen.getByTestId('metric-mean')).toHaveTextContent('7,40')
    expect(screen.getByRole('table', { name: 'Tabla de frecuencias' })).toHaveTextContent('0,3000')
    await user.clear(input)
    await user.type(input, '1, hola')
    expect(screen.getByRole('alert')).toHaveTextContent('no es un número válido')
    await user.clear(input)
    await user.type(input, '1, 2, 3')
    expect(screen.getByTestId('metric-mean')).toHaveTextContent('2,00')
    await user.click(screen.getByRole('button', { name: 'Limpiar' }))
    expect(input).toHaveValue('')
    expect(screen.queryByRole('table')).not.toBeInTheDocument()
  })

  it('opens the requested exact statistical lessons only through help dialogs', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.type(screen.getByLabelText('Serie de datos'), '1, 2, 2, 5')
    expect(screen.getByTestId('metric-mean')).toHaveTextContent('2,50')
    expect(screen.getByTestId('metric-median')).toHaveTextContent('2')
    expect(screen.getByTestId('metric-mode')).toHaveTextContent('2')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.queryByText(/El procedimiento para obtener la moda/)).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Ayuda: Media aritmética' }))
    let dialog = screen.getByRole('dialog', { name: 'Media aritmética' })
    expect(within(dialog).getByRole('img', { name: 'Facundo Moriconi' })).toBeInTheDocument()
    expect(dialog).toHaveTextContent('Multiplicar cada dato')
    expect(dialog).toHaveTextContent('Sumar todos los resultados de esas multiplicaciones.')
    expect(dialog).toHaveTextContent('Dividir esa suma total por la cantidad total de datos')
    expect(within(dialog).getByLabelText('Media aritmética: suma de cada valor por su frecuencia, dividida por n')).toBeInTheDocument()
    await user.click(within(dialog).getByRole('button', { name: 'Cerrar ayuda' }))
    await user.click(screen.getByRole('button', { name: 'Ayuda: Mediana' }))
    dialog = screen.getByRole('dialog', { name: 'Mediana' })
    expect(within(dialog).getByRole('img', { name: 'Franco Aguirre' })).toBeInTheDocument()
    expect(dialog).toHaveTextContent('Ordenar todos los números de menor a mayor.')
    expect(dialog).toHaveTextContent('Si la cantidad de datos es impar')
    expect(dialog).toHaveTextContent('sumar los dos números centrales y dividirlos por 2.')
    await user.click(within(dialog).getByRole('button', { name: 'Cerrar ayuda' }))
    const modeTrigger = screen.getByRole('button', { name: 'Ayuda: Moda' })
    await user.click(modeTrigger)
    dialog = screen.getByRole('dialog', { name: 'Moda' })
    expect(dialog).toHaveTextContent('El procedimiento para obtener la moda consiste en contabilizar y comparar las frecuencias de todos los datos, para luego seleccionar el que más se repite. Al aplicar este proceso, el resultado puede ser único, múltiple si varios valores empatan en la frecuencia máxima (ej: 7 autos rojos y 7 azules), o incluso nulo si ningún dato destaca sobre el resto.')
    await user.click(within(dialog).getByRole('button', { name: 'Cerrar ayuda' }))
    expect(modeTrigger).toHaveFocus()
    expect(screen.queryByText(/Σfi|Σhi|Comprendé los cálculos|No solo resultados|conservan su precisión interna/)).not.toBeInTheDocument()
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Tipo de gráfico'), 'grouped')
    expect(screen.getByTestId('metric-median')).toHaveTextContent('2')
  })

  it('builds manual events and computes exclusive and nonexclusive intersections', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    await user.type(screen.getByLabelText('Elementos del espacio'), 'L, M, P, S')
    expect(screen.getByTestId('space-count')).toHaveTextContent('|Ω| = 6')
    await user.click(screen.getByLabelText('El orden importa'))
    expect(screen.getByTestId('space-count')).toHaveTextContent('12')
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    const eventA = screen.getByTestId('event-A')
    expect(within(eventA).getByText('Imposible')).toBeInTheDocument()
    await user.click(within(eventA).getByRole('button', { name: 'L · P' }))
    await user.click(within(eventA).getByRole('button', { name: 'P · L' }))
    expect(screen.getByTestId('event-probability-A')).toHaveTextContent('16,67%')
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    const eventB = screen.getByTestId('event-B')
    await user.click(within(eventB).getByRole('button', { name: 'M · S' }))
    expect(screen.getByTestId('intersection-result')).toHaveAttribute('data-exclusive', 'true')
    await user.click(within(eventB).getByRole('button', { name: 'L · P' }))
    expect(screen.getByTestId('intersection-result')).toHaveAttribute('data-exclusive', 'false')
    await user.click(within(eventA).getByRole('button', { name: 'Seleccionar todos' }))
    expect(within(eventA).getByText('Seguro')).toBeInTheDocument()
    expect(screen.getByTestId('event-probability-A')).toHaveTextContent('100,00%')
  })

  it('only selects without repetition and resets events when ordering changes', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    await user.type(screen.getByLabelText('Elementos del espacio'), 'Único')
    expect(screen.getByTestId('space-count')).toHaveTextContent('|Ω| = 0')
    await user.clear(screen.getByLabelText('Elementos del espacio'))
    await user.type(screen.getByLabelText('Elementos del espacio'), 'A, B, C')
    expect(screen.getByTestId('space-count')).toHaveTextContent('|Ω| = 3')
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    expect(screen.getByTestId('event-probability-A')).toHaveTextContent('0,00%')
    await user.click(screen.getByLabelText('El orden importa'))
    expect(screen.getByTestId('space-count')).toHaveTextContent('|Ω| = 6')
    expect(screen.queryByTestId('event-A')).not.toBeInTheDocument()
  })
  it('switches themes and retains input while navigating', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.type(screen.getByLabelText('Serie de datos'), '1, 2, 3')
    await user.click(screen.getByRole('button', { name: 'Cambiar tema' }))
    expect(document.documentElement.classList.contains('dark')).toBe(true)
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    await user.click(screen.getByRole('button', { name: /Estadística descriptiva/ }))
    expect(screen.getByLabelText('Serie de datos')).toHaveValue('1, 2, 3')
  })

  it('presents both teachers with their locally bundled illustrations', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: 'Profesores' }))
    for (const name of ['Facundo Moriconi', 'Franco Aguirre']) {
      const profile = screen.getByRole('article', { name: `Perfil de ${name}` })
      expect(within(profile).getByRole('heading', { name })).toBeInTheDocument()
      const portrait = within(profile).getByRole('img', { name })
      expect(portrait.getAttribute('src')).not.toMatch(/^https?:/)
      expect(portrait).toHaveAttribute('width')
      expect(portrait.getAttribute('src')).toMatch(/\.svg/)
    }
    expect(screen.getByText(/no son citas textuales/i)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /Estadística descriptiva/ }))
    expect(screen.getByLabelText('Serie de datos')).toHaveValue('')
  })

  it('accompanies educational explanations with a teacher without changing calculations', async () => {
    const user = userEvent.setup()
    render(<App />)
    const checkHelp = async (name: string, content: RegExp) => {
      await user.click(screen.getByRole('button', { name: `Ayuda: ${name}` }))
      const dialog = screen.getByRole('dialog', { name })
      expect(dialog).toHaveTextContent(content)
      expect(within(dialog).getByRole('img', { name: /Facundo Moriconi|Franco Aguirre/ })).toBeInTheDocument()
      await user.click(within(dialog).getByRole('button', { name: 'Cerrar ayuda' }))
    }
    await user.type(screen.getByLabelText('Serie de datos'), '1, 2, 2, 5')
    expect(screen.getByTestId('metric-mean')).toHaveTextContent('2,50')
    await checkHelp('Interpretar el gráfico', /Cada barra representa un valor distinto/)
    await user.selectOptions(screen.getByLabelText('Tipo de gráfico'), 'grouped')
    await checkHelp('Interpretar el gráfico', /Los intervalos tienen la misma amplitud/)
    await user.click(screen.getByRole('button', { name: /Guía rápida/ }))
    const guide = screen.getByRole('dialog', { name: 'Guía rápida' })
    expect(guide).toHaveTextContent(/Las explicaciones de media, mediana y moda/)
    await user.click(within(guide).getByRole('button', { name: 'Cerrar ayuda' }))
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    await user.type(screen.getByLabelText('Elementos del espacio'), 'A, B, C')
    await checkHelp('Procedimiento: cardinalidad del espacio', /C\(n, k\)/)
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    const event = screen.getByTestId('event-A')
    await user.click(within(event).getByRole('button', { name: 'Ayuda: Ver procedimiento de A' }))
    const procedure = screen.getByRole('dialog', { name: 'Ver procedimiento de A' })
    expect(procedure).toHaveTextContent('P(A) = 0/3')
    expect(procedure).toHaveTextContent(/No contiene resultados: no puede ocurrir/)
    await user.click(within(procedure).getByRole('button', { name: 'Cerrar ayuda' }))
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    await checkHelp('Intersección de eventos', /Los eventos son mutuamente excluyentes/)
    await user.clear(screen.getByLabelText('Elementos del espacio'))
    await user.type(screen.getByLabelText('Elementos del espacio'), 'A, B, C, D, E, F, G, H, I, J')
    await user.clear(screen.getByLabelText('Cantidad a seleccionar (k)'))
    await user.type(screen.getByLabelText('Cantidad a seleccionar (k)'), '3')
    await user.click(screen.getByLabelText('El orden importa'))
    expect(screen.getByText(/solo enumeramos espacios de hasta 400 resultados/)).toBeInTheDocument()
  })

  it('keeps only the key help dialogs in probability', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    await user.type(screen.getByLabelText('Elementos del espacio'), 'A, B, C')
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    const helps = screen.getAllByRole('button', { name: /^Ayuda: / }).map(button => button.getAttribute('aria-label'))
    expect(helps).toEqual(['Ayuda: Guía rápida', 'Ayuda: Procedimiento: cardinalidad del espacio', 'Ayuda: Ver procedimiento de A', 'Ayuda: Ver procedimiento de B', 'Ayuda: Intersección de eventos'])
    expect(screen.getByText(/Separá nombres con comas o saltos de línea/)).toBeInTheDocument()
  })

  it('assumes equally likely outcomes without a confirmation checkbox', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    expect(screen.queryByRole('checkbox', { name: /equiprobables/ })).not.toBeInTheDocument()
    expect(screen.getByText(/Se asume que todos los resultados son igualmente probables/)).toBeInTheDocument()
    expect(screen.getByLabelText('El orden importa')).not.toBeChecked()
  })

  it('keeps independent plain-text event statements through selections and navigation', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    await user.type(screen.getByLabelText('Elementos del espacio'), 'A, B, C')
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    const statementA = screen.getByLabelText('Enunciado del evento A')
    expect(statementA).toHaveValue('')
    const textA = 'Seleccionar dos estudiantes.\nQue ambos sean varones.'
    await user.click(statementA)
    await user.paste(textA)
    expect(screen.getByTestId('event-probability-A')).toHaveTextContent('0,00%')
    const eventA = screen.getByTestId('event-A')
    await user.click(within(eventA).getByRole('button', { name: 'A · B' }))
    expect(statementA).toHaveValue(textA)
    expect(screen.getByTestId('event-probability-A')).toHaveTextContent('33,33%')
    await user.click(screen.getByRole('button', { name: /Crear evento/ }))
    expect(screen.getByLabelText('Enunciado del evento B')).toHaveValue('')
    await user.click(screen.getByLabelText('Enunciado del evento B'))
    await user.paste('Un enunciado distinto para B.')
    await user.click(within(eventA).getByRole('button', { name: 'Seleccionar todos' }))
    expect(statementA).toHaveValue(textA)
    expect(screen.getByTestId('event-probability-A')).toHaveTextContent('100,00%')
    await user.click(within(eventA).getByRole('button', { name: 'Vaciar' }))
    expect(statementA).toHaveValue(textA)
    await user.click(screen.getByRole('button', { name: 'Profesores' }))
    await user.click(screen.getByRole('button', { name: /^Probabilidad/ }))
    expect(screen.getByLabelText('Enunciado del evento A')).toHaveValue(textA)
    expect(screen.getByLabelText('Enunciado del evento B')).toHaveValue('Un enunciado distinto para B.')
    await user.click(screen.getByRole('button', { name: 'Eliminar evento B' }))
    expect(screen.queryByLabelText('Enunciado del evento B')).not.toBeInTheDocument()
    await user.click(screen.getByLabelText('El orden importa'))
    expect(screen.queryByLabelText('Enunciado del evento A')).not.toBeInTheDocument()
  })
})
